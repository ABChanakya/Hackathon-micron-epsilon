#!/usr/bin/env python3
"""Reproduce the offline PDF fonts. Requires fonttools==4.61.1; downloads pinned OFL sources."""
from pathlib import Path
import concurrent.futures, hashlib, json, urllib.request, tempfile
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT=Path(__file__).resolve().parents[1]
DEST=ROOT/'dist/assets/pdf-fonts'
CJK='523d033d6cb47f4a80c58a35753646f5c3608a78'
LATIN='ffebf8c1ee449e544955a7e813c54f9b73848eac'
CACHE=Path(tempfile.gettempdir())/'micro-epsilon-pdf-font-sources'/f'{CJK}-{LATIN}'
SOURCES={
 'Latin-Regular':f'https://raw.githubusercontent.com/notofonts/noto-fonts/{LATIN}/hinted/ttf/NotoSans/NotoSans-Regular.ttf',
 'Latin-Bold':f'https://raw.githubusercontent.com/notofonts/noto-fonts/{LATIN}/hinted/ttf/NotoSans/NotoSans-Bold.ttf',
 **{f'{region}-VF':f'https://raw.githubusercontent.com/notofonts/noto-cjk/{CJK}/Sans/Variable/TTF/Subset/NotoSans{region}-VF.ttf' for region in ['SC','JP','KR']},
 'LICENSE-Latin':f'https://raw.githubusercontent.com/notofonts/noto-fonts/{LATIN}/LICENSE',
 'LICENSE-CJK':f'https://raw.githubusercontent.com/notofonts/noto-cjk/{CJK}/LICENSE',
}

def fetch(item):
 name,url=item
 path=CACHE/name
 if not path.exists():
  with urllib.request.urlopen(url,timeout=120) as response: path.write_bytes(response.read())
 return name,path

def ranges(values):
 result=[]
 for cp in sorted(values):
  if result and cp==result[-1][1]+1:result[-1][1]=cp
  else:result.append([cp,cp])
 return result

def main():
 DEST.mkdir(parents=True,exist_ok=True);CACHE.mkdir(parents=True,exist_ok=True)
 downloaded=dict(concurrent.futures.ThreadPoolExecutor(max_workers=5).map(fetch,SOURCES.items()))
 manifest={}
 for name,path in downloaded.items():
  if name.startswith('LICENSE'):
   (DEST/(name+'.txt')).write_bytes(path.read_bytes());continue
  if name.endswith('-VF'):
   family=name.split('-')[0]
   for weight,style in [(400,'Regular'),(700,'Bold')]:
    font=TTFont(path)
    axes={axis.axisTag:(weight if axis.axisTag=='wght' else axis.defaultValue) for axis in font['fvar'].axes}
    instantiateVariableFont(font,axes,inplace=True)
    # Give the generated static instance an explicit weight and style.
    font['OS/2'].usWeightClass=weight
    font.recalcTimestamp=False
    target=DEST/f'NotoSans{family}-{style}.ttf';font.save(target)
    manifest[f'{family}-{style}']={'file':target.name,'ranges':ranges(font.getBestCmap()),'sha256':hashlib.sha256(target.read_bytes()).hexdigest(),'source':SOURCES[name]}
  else:
   target=DEST/f'NotoSans-{name.split("-")[1]}.ttf';target.write_bytes(path.read_bytes())
   font=TTFont(target)
   manifest[name]={'file':target.name,'ranges':ranges(font.getBestCmap()),'sha256':hashlib.sha256(target.read_bytes()).hexdigest(),'source':SOURCES[name]}
 (DEST/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
 (ROOT/'dist/pdf-font-data.js').write_text('// Generated by scripts/build-pdf-fonts.py; pinned sources and licenses are beside the font assets.\nexport default '+json.dumps(manifest,separators=(',',':'))+';\n')
 print(json.dumps({k:{'file':v['file'],'bytes':(DEST/v['file']).stat().st_size} for k,v in manifest.items()},indent=2))
if __name__=='__main__':main()
